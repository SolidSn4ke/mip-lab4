#pragma once
#include <types.h>

/**
 * @brief Представляет цвет в 8-битном формате RGB.
 *
 * Используется для хранения цвета изображения в диапазоне 0–255
 * (после преобразования из float/HDR представления).
 */
class RGB8 {
  public:
    uint8_t r, g, b;

    /**
     * @brief Создаёт цвет RGB.
     *
     * @param r Красный канал (0–255).
     * @param g Зелёный канал (0–255).
     * @param b Синий канал (0–255).
     */
    RGB8(uint8_t r = 0, uint8_t g = 0, uint8_t b = 0);
};